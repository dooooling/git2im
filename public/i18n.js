let currentLocale = localStorage.getItem("gim_locale") || (navigator.language?.startsWith("zh") ? "zh-CN" : "en");

export function getLocale() {
  return currentLocale;
}

export function setLocale(lang) {
  if (locales[lang]) {
    currentLocale = lang;
    localStorage.setItem("gim_locale", lang);
  }
}

/**
 * 翻译指定 Key 的文本
 */
export function t(key, params = {}) {
  const dict = locales[currentLocale] || locales["zh-CN"];
  let text = dict[key] || locales["zh-CN"][key] || key;

  for (const [k, v] of Object.entries(params)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
  }

  return text;
}
